"""Generating the preventive files, tailored to what a repository contains.

Two defaults here are opinions earned rather than assumed.

**Dependabot defaults to security updates only.** Rolling a config with weekly
version updates across 38 repositories produced 302 open pull requests in a few
hours. At that volume nobody reads them, and an unread dependency pull request
is worse than none because it also buries the one that mattered.
`open-pull-requests-limit: 0` disables version updates; GitHub does not apply
that limit to security updates, so vulnerability fixes still arrive.

**The limit is written into every ecosystem block explicitly.** Omitting it
does not mean zero, it means the default of five. A config that sets the key on
its npm block and leaves it off its github-actions block quietly keeps opening
pull requests, which is precisely the bug that shipped before this was a
function.
"""

from __future__ import annotations

from pathlib import Path

#: gitleaks release pinned by version and verified by digest. Both are checked
#: in CI by `allclear selftest`, so a stale pin fails loudly rather than
#: silently downloading something else.
GITLEAKS_VERSION = "8.30.1"
GITLEAKS_SHA256_LINUX_X64 = "551f6fc83ea457d62a0d98237cbad105af8d557003051f41f3e7ca7b3f2470eb"
CHECKOUT_SHA = "3d3c42e5aac5ba805825da76410c181273ba90b1"  # actions/checkout v7.0.1


def _eco_block(eco: str, directory: str, security_only: bool, interval: str = "weekly") -> str:
    limit = 0 if security_only else 5
    return f"""\
  - package-ecosystem: "{eco}"
    directory: "{directory}"
    schedule:
      interval: "{interval}"
    # Written explicitly on EVERY ecosystem. Leaving this key out does not mean
    # zero, it means the default of 5 — which is how a config that looks
    # security-only keeps opening version-update pull requests.
    open-pull-requests-limit: {limit}
    groups:
      security:
        applies-to: security-updates
        patterns: ["*"]
"""


def dependabot(root: str | Path, security_only: bool = True) -> str | None:
    """A dependabot.yml describing only the ecosystems this repo really has."""
    root = Path(root)
    blocks: list[str] = []

    lock_dirs: set[str] = set()
    for pattern in ("package-lock.json", "pnpm-lock.yaml", "yarn.lock",
                    "*/package-lock.json", "*/pnpm-lock.yaml",
                    "apps/*/package-lock.json", "apps/*/pnpm-lock.yaml"):
        for p in root.glob(pattern):
            rel = p.parent.relative_to(root).as_posix()
            lock_dirs.add("/" if rel == "." else f"/{rel}")
    for d in sorted(lock_dirs)[:10]:
        blocks.append(_eco_block("npm", d, security_only))

    py_dirs: set[str] = set()
    for pattern in ("requirements*.txt", "pyproject.toml",
                    "*/requirements*.txt", "*/pyproject.toml",
                    "apps/*/requirements*.txt"):
        for p in root.glob(pattern):
            parts = {s.lower() for s in p.parts}
            if parts & {"fixtures", "fixture", "node_modules", ".venv"}:
                continue  # deliberately-vulnerable sample trees are not dependencies
            rel = p.parent.relative_to(root).as_posix()
            py_dirs.add("/" if rel == "." else f"/{rel}")
    for d in sorted(py_dirs)[:10]:
        blocks.append(_eco_block("pip", d, security_only))

    if (root / ".github" / "workflows").is_dir():
        blocks.append(_eco_block("github-actions", "/", security_only, interval="monthly"))
    if list(root.glob("**/Dockerfile"))[:1]:
        blocks.append(_eco_block("docker", "/", security_only, interval="monthly"))

    if not blocks:
        return None

    mode = ("Security updates only. Version updates are disabled "
            "(open-pull-requests-limit: 0), which GitHub does not apply to security updates."
            if security_only else
            "Security and version updates, with minor/patch grouped.")
    header = f"""\
version: 2

# Generated by allclear. {mode}
#
# Ecosystems listed below are the ones this repository actually contains;
# deliberately-vulnerable fixture trees are excluded so the scanner does not
# raise pull requests against test data.

updates:
"""
    return header + "\n".join(blocks)


def security_workflow() -> str:
    """A secret-scan + dependency-audit workflow with no third-party actions."""
    return f"""\
# Generated by allclear.
#
# gitleaks runs from its official release BINARY, pinned to a version and
# verified against the published SHA-256, rather than through a third-party
# Action. That avoids trusting a mutable tag, avoids the licence gate some
# accounts hit, and makes the result reproducible locally with the same binary.
#
# actions/checkout is pinned to a commit SHA. A tag can be moved; a SHA cannot.
#
# The dependency audit reports without failing the build: an advisory with no
# available fix would otherwise leave a permanently red check, and a check that
# is always red is one everybody learns to ignore. Dependabot is what opens the
# fix.

name: Security

on:
  pull_request:
  push:
    branches: [main]
  schedule:
    - cron: "17 4 * * 1"
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: security-${{{{ github.workflow }}}}-${{{{ github.ref }}}}
  cancel-in-progress: true

env:
  GITLEAKS_VERSION: "{GITLEAKS_VERSION}"
  GITLEAKS_SHA256: "{GITLEAKS_SHA256_LINUX_X64}"

jobs:
  secrets:
    name: Secret scan
    runs-on: ubuntu-latest
    timeout-minutes: 10
    steps:
      - uses: actions/checkout@{CHECKOUT_SHA} # v7.0.1
        with:
          # Full history on the weekly run; shallow on a pull request, where
          # only the diff is in question.
          fetch-depth: ${{{{ github.event_name == 'schedule' && 0 || 1 }}}}

      - name: Install gitleaks (pinned, checksum-verified)
        run: |
          set -euo pipefail
          F="gitleaks_${{GITLEAKS_VERSION}}_linux_x64.tar.gz"
          curl -fsSL -o "$F" \\
            "https://github.com/gitleaks/gitleaks/releases/download/v${{GITLEAKS_VERSION}}/$F"
          echo "${{GITLEAKS_SHA256}}  $F" | sha256sum -c -
          tar -xzf "$F" gitleaks
          chmod +x gitleaks

      - name: Scan
        run: |
          set -euo pipefail
          if [ "${{{{ github.event_name }}}}" = "schedule" ]; then
            ./gitleaks git . --log-opts=--all --redact --no-banner --verbose
          else
            ./gitleaks dir . --redact --no-banner --verbose
          fi

  dependencies:
    name: Dependency audit
    runs-on: ubuntu-latest
    timeout-minutes: 15
    steps:
      - uses: actions/checkout@{CHECKOUT_SHA} # v7.0.1
      - name: Audit
        shell: bash
        run: |
          if [ -f pnpm-lock.yaml ]; then
            corepack enable && pnpm audit --audit-level high || true
          elif [ -f package-lock.json ]; then
            npm audit --audit-level=high || true
          elif ls requirements*.txt >/dev/null 2>&1; then
            python -m pip install --quiet pip-audit
            for r in requirements*.txt; do pip-audit -r "$r" || true; done
          else
            echo "No recognised lockfile at the repository root; nothing to audit."
          fi
"""


def security_policy(contact: str = "the maintainer address on this account's GitHub profile") -> str:
    return f"""\
# Security Policy

## Reporting a vulnerability

Please report security issues **privately**, not in a public issue.

Use GitHub's private vulnerability reporting on this repository:
**Security → Report a vulnerability**. If that is unavailable, contact
{contact} with `SECURITY` in the subject.

Please include what the issue is, how to reproduce it, the affected version or
commit, and anything you already know about impact.

**Please do not** open a public issue, a pull request containing an exploit, or
a public discussion thread for an unfixed vulnerability.

## What to expect

- Acknowledgement within **7 days**.
- An assessment, and either a fix or a clear explanation of why something is not
  considered a vulnerability, within **30 days** where that is achievable.
- Credit in the release notes if you would like it — please say so.

Response times are best-effort and stated honestly rather than optimistically.

## Scope

In scope: this repository's own source, its build and release workflows, and
its dependency manifests.

Out of scope: third-party dependencies with an existing public advisory —
Dependabot raises those. Directories documented as deliberately insecure
fixtures are not vulnerabilities; findings inside them are expected.
"""


def write_all(root: str | Path, security_only: bool = True,
              allowlist_text: str | None = None, force: bool = False) -> "dict[str, str]":
    """Write the baseline into a repository. Returns {path: action}."""
    root = Path(root)
    actions: dict[str, str] = {}

    def put(rel: str, content: str) -> None:
        dest = root / rel
        if dest.exists() and not force:
            actions[rel] = "kept (already present)"
            return
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(content, encoding="utf-8")
        actions[rel] = "written"

    db = dependabot(root, security_only=security_only)
    if db:
        put(".github/dependabot.yml", db)
    else:
        actions[".github/dependabot.yml"] = "skipped (no dependency manifests to watch)"

    wf_dir = root / ".github" / "workflows"
    existing = [p.name.lower() for p in wf_dir.glob("*.y*ml")] if wf_dir.is_dir() else []
    if any(k in n for n in existing for k in ("security", "gitleaks", "secret", "codeql")):
        actions[".github/workflows/security.yml"] = "skipped (a security workflow already exists)"
    else:
        put(".github/workflows/security.yml", security_workflow())

    put("SECURITY.md", security_policy())
    if allowlist_text:
        put(".gitleaksignore", allowlist_text)
    return actions
