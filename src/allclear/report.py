"""Rendering findings as something a person will actually read."""

from __future__ import annotations

from collections import Counter

from .verdict import Finding, SEVERITY_ORDER

SEV_MARK = {"critical": "CRIT", "high": "HIGH", "medium": "MED ", "low": "LOW ", "info": "INFO"}


def summary_lines(findings: "list[Finding]", repos: int) -> "list[str]":
    actionable = [f for f in findings if f.actionable]
    quiet = [f for f in findings if not f.actionable]
    sev = Counter(f.severity for f in actionable)
    verd = Counter(f.verdict for f in quiet)
    lines = [
        f"repositories examined : {repos}",
        f"findings that need you: {len(actionable)}"
        + (f"  ({', '.join(f'{sev[s]} {s}' for s in SEVERITY_ORDER if sev[s])})" if actionable else ""),
        f"findings explained away: {len(quiet)}"
        + (f"  ({', '.join(f'{n} {v}' for v, n in verd.most_common())})" if quiet else ""),
    ]
    return lines


def text(findings: "list[Finding]", repos: int, show_quiet: bool = False) -> str:
    out = ["", "allclear", "=" * 8, ""]
    out += summary_lines(findings, repos)
    actionable = sorted(
        [f for f in findings if f.actionable],
        key=lambda f: (SEVERITY_ORDER.index(f.severity) if f.severity in SEVERITY_ORDER else 9, f.repo),
    )
    if actionable:
        out += ["", "NEEDS ACTION", "-" * 12]
        for f in actionable:
            where = f" {f.path}" + (f":{f.line}" if f.line else "") if f.path else ""
            out.append(f"  [{SEV_MARK.get(f.severity, f.severity)}] {f.repo}{where}")
            out.append(f"         {f.title}")
            if f.reason:
                out.append(f"         why: {f.reason}")
            if f.remediation:
                out.append(f"         fix: {f.remediation}")
    else:
        out += ["", "Nothing needs action.", ""]
    if show_quiet:
        quiet = [f for f in findings if not f.actionable]
        if quiet:
            out += ["", "EXPLAINED (no action)", "-" * 21]
            for f in quiet:
                where = f" {f.path}" + (f":{f.line}" if f.line else "") if f.path else ""
                out.append(f"  [{f.verdict}] {f.repo}{where} — {f.reason}")
    out.append("")
    return "\n".join(out)


def markdown(findings: "list[Finding]", repos: int, coverage_gaps: "list[str]" | None = None,
             blocked: "list[Finding]" | None = None) -> str:
    actionable = [f for f in findings if f.actionable]
    quiet = [f for f in findings if not f.actionable]
    sev = Counter(f.severity for f in actionable)
    md = ["# allclear report", "",
          "> Generated by [allclear](https://github.com/itsshreyasbhardwaj-design/allclear). ",
          "> Contains no credential values — findings are described by location and masked length only.",
          "", "## Summary", "",
          "| | |", "|---|---|",
          f"| Repositories examined | **{repos}** |",
          f"| Findings that need action | **{len(actionable)}** |",
          f"| Findings explained away | {len(quiet)} |"]
    for s in SEVERITY_ORDER:
        if sev[s]:
            md.append(f"| &nbsp;&nbsp;{s} | {sev[s]} |")
    md += [""]
    if blocked:
        md += ["## Blocked by plan", "",
               "These are not misconfigurations. The plan does not offer the control, so the",
               "honest options are to upgrade, change visibility, or accept the risk knowingly.", "",
               "| Repository | Control | Detail |", "|---|---|---|"]
        for f in blocked:
            md.append(f"| `{f.repo}` | {f.check} | {f.reason} |")
        md += [""]
    if coverage_gaps:
        md += ["## Coverage limits", ""] + [f"- {g}" for g in coverage_gaps] + [""]
    if actionable:
        md += ["## Needs action", "", "| Severity | Repository | Finding | Why | Fix |", "|---|---|---|---|---|"]
        for f in sorted(actionable, key=lambda f: SEVERITY_ORDER.index(f.severity)
                        if f.severity in SEVERITY_ORDER else 9):
            loc = f" (`{f.path}`)" if f.path else ""
            md.append(f"| **{f.severity}** | `{f.repo}` | {f.title}{loc} | {f.reason} | `{f.remediation}` |")
        md += [""]
    else:
        md += ["## Needs action", "", "Nothing. Every finding was explained.", ""]
    if quiet:
        md += ["## Explained away", "",
               "Each of these was classified with a stated reason rather than suppressed.", "",
               "| Verdict | Repository | Location | Reason |", "|---|---|---|---|"]
        for f in quiet:
            md.append(f"| {f.verdict} | `{f.repo}` | `{f.path or '-'}` | {f.reason} |")
        md += [""]
    return "\n".join(md)
