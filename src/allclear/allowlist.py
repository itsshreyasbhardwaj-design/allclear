"""Writing a `.gitleaksignore` that stays useful.

The obvious way to silence a known-benign finding is a path glob: ignore
`**/*.test.ts` and the noise goes away. So does the signal. A real credential
pasted into a test file then scans clean forever, and test files are a very
ordinary place for a real credential to end up during debugging.

gitleaks accepts *fingerprints* — `path:rule:line`, optionally commit-prefixed —
which identify one finding at one place. Allowlisting those keeps the scan
green on what has been reviewed while still failing on anything new, including
anything new in the very same file. That property is the whole point, so this
module asserts it in `verify()` rather than trusting it.
"""

from __future__ import annotations

from .verdict import Finding

HEADER = """\
# gitleaks allowlist — audited exceptions only. Generated by allclear.
#
# Every entry below was classified and the reason is recorded beside it. None
# is believed to be a live credential.
#
# These are FINGERPRINTS (path:rule:line), not path globs, on purpose: a
# fingerprint pins one finding at one location, so a NEW secret added to any of
# these same files still fails the scan. Replacing them with globs would make
# the scan permanently blind to the files most likely to collect a real
# credential by accident.
#
# If an entry here turns out to be real, DELETE the line rather than editing it,
# so the scanner reports it again.
"""


def build(findings: "list[Finding]") -> str:
    """Render a `.gitleaksignore` from the non-actionable findings."""
    entries: list[tuple[str, str, str]] = []
    seen: set[str] = set()
    for f in findings:
        if f.actionable or not f.fingerprint or f.fingerprint in seen:
            continue
        seen.add(f.fingerprint)
        entries.append((f.fingerprint, f.path or "?", f"{f.verdict}: {f.reason}"))
    if not entries:
        return HEADER + "\n# Nothing to allowlist: no benign findings were classified.\n"
    out = [HEADER]
    for fp, path, why in sorted(entries, key=lambda e: (e[1], e[0])):
        out.append(f"\n# {path}\n#   {why}\n{fp}")
    return "\n".join(out) + "\n"


def verify(allowlist_text: str, findings: "list[Finding]") -> "list[str]":
    """Check the allowlist does not hide anything actionable.

    Returns the list of problems found; empty means the allowlist is safe.
    """
    listed = {
        line.strip()
        for line in allowlist_text.splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    }
    problems = []
    for f in findings:
        if f.actionable and f.fingerprint and f.fingerprint in listed:
            problems.append(
                f"{f.fingerprint} is allowlisted but classified '{f.verdict}' "
                f"({f.reason}) — an actionable finding must never be silenced"
            )
    globs = [l for l in listed if "*" in l]
    for g in globs:
        problems.append(
            f"{g!r} looks like a glob. gitleaks allowlists are fingerprints; a glob "
            "would hide future findings in the same place."
        )
    return problems
